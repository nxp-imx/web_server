#!/bin/bash
function gnss_init(){
    i2ctransfer -y 3 w37@0x42 0xb5 0x62 0x06 0x8a \
        0x1d 0x00 \
        0x00 0x01 0x00 0x00 \
        0x2e 0x00 0xa3 0x10 0x01 \
        0x2f 0x00 0xa3 0x10 0x01 \
        0x31 0x00 0xa3 0x10 0x01 \
        0x33 0x00 0xa3 0x10 0x01 \
        0x35 0x00 0xa3 0x10 0x01 \
        0x28 0x0f
}

function gnss_get(){
    i2ctransfer -y 3 w8@0x42 0xB5 0x62 0x0a 0x02 0x00 0x00 0x08 0x19 r1500
}



# ================ [ main ] ================

myself=$0
while [ $# -gt 0 ]
do
	echo -e "[$1]"
	case "$1" in
		init)
            gnss_init;;
		get)
            gnss_get;;
		*) echo -n "Error, Unsupported cmd: [$1]"; exit -1;;
	esac
	shift
done